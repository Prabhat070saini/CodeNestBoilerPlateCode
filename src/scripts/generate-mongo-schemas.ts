import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

type SchemaDefinition = {
  model: string;
  schema: string;
  importPath: string;
};

const projectRoot = resolve(__dirname, '../..');
const srcRoot = join(projectRoot, 'src');

const schemasRoot = join(projectRoot, 'src', 'apis');
const outputFile = join(
  srcRoot,
  'core',
  'database',
  'no_sql',
  'no_sql.schemas.generated.ts',
);

function findSchemaFiles(directory: string): string[] {
  if (!existsSync(directory)) return [];

  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = join(directory, entry.name);
    if (entry.isDirectory()) return findSchemaFiles(entryPath);
    return entry.name.endsWith('.schema.ts') ? [entryPath] : [];
  });
}

const schemas: SchemaDefinition[] = findSchemaFiles(schemasRoot)
  .sort()
  .map((file) => {
    const source = readFileSync(file, 'utf8');
    const classMatch = source.match(/export\s+class\s+(\w+)/);
    const schemaMatch = source.match(
      /export\s+const\s+(\w+Schema)\s*=\s*SchemaFactory\.createForClass/,
    );

    if (!classMatch || !schemaMatch) {
      throw new Error(
        `Invalid Mongo schema: ${relative(projectRoot, file)}. ` +
          'Export a class and a SchemaFactory schema constant.',
      );
    }

    const importPath = relative(dirname(outputFile), file)
      .replace(/\\/g, '/')
      .replace(/\.ts$/, '');

    return {
      model: classMatch[1],
      schema: schemaMatch[1],
      importPath: importPath.startsWith('.') ? importPath : `./${importPath}`,
    };
  });

const imports = schemas
  .map(
    ({ model, schema, importPath }) =>
      `import { ${model}, ${schema} } from '${importPath}';`,
  )
  .join('\n');
const definitions = schemas
  .map(({ model, schema }) => `  { name: ${model}.name, schema: ${schema} },`)
  .join('\n');
const generatedSource =
  '// Generated by `npm run mongo:schemas:generate`. Do not edit manually.\n' +
  `${imports}\n\nexport const MONGODB_SCHEMAS = [\n${definitions}\n];\n`;

if (
  !existsSync(outputFile) ||
  readFileSync(outputFile, 'utf8') !== generatedSource
) {
  writeFileSync(outputFile, generatedSource);
}

/* eslint-disable-next-line no-console */
console.log(
  `Generated Mongo schema registry with ${schemas.length} schema(s).`,
);
